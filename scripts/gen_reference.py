"""Generate the reference pages of the documentation from the code.

    python scripts/gen_reference.py           # write the pages
    python scripts/gen_reference.py --check   # exit 1 if a committed page is out of date

Pages written (relative to the project folder):
    docs/reference/configuration.md   run settings, from RunConfig
    docs/reference/cli.md             commands and options, from the argparse parser
    docs/reference/templates.md       built-in prompt templates, from the template files

The output only depends on the code, not on the terminal width, the operating system or the
Python version. tests/test_docs_reference.py fails when a committed page differs.
"""

from __future__ import annotations

import argparse
import inspect
import re
import sys
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from codebook_annotator import config as config_module  # noqa: E402
from codebook_annotator.cli import build_parser  # noqa: E402
from codebook_annotator.config import RunConfig  # noqa: E402
from codebook_annotator.prompt import available_templates, load_template  # noqa: E402

HEADER = "<!-- Generated by scripts/gen_reference.py. Do not edit by hand. -->\n\n"


def _cell(text: str) -> str:
    """Make text safe inside a Markdown table cell. Placeholders like <name> are shown as code."""
    text = re.sub(r"(<[^<>\s]+>)", r"`\1`", str(text))
    return text.replace("|", "\\|").replace("\n", " ")


# ── configuration ──────────────────────────────────────────────────────────────────────────────

def _type_name(annotation) -> str:
    if typing.get_origin(annotation) is typing.Literal:
        return "one of: " + ", ".join(f"`{a}`" for a in typing.get_args(annotation))
    args = typing.get_args(annotation)
    if args:
        inner = [a for a in args if a is not type(None)]
        base = _type_name(inner[0]) if len(inner) == 1 else " or ".join(_type_name(a) for a in inner)
        return base + (" or empty" if type(None) in args else "")
    names = {str: "text", int: "integer", float: "number", bool: "true/false", Path: "path"}
    return names.get(annotation, getattr(annotation, "__name__", str(annotation)))


def _default(field) -> str:
    if field.is_required():
        return "**required**"
    d = field.default
    if d is None:
        return "empty"
    if isinstance(d, bool):
        return f"`{str(d).lower()}`"
    return f"`{d}`"


def _groups() -> list[tuple[str, list[str]]]:
    """Field groups, taken from the comment lines inside the RunConfig class body."""
    src = inspect.getsource(config_module.RunConfig)
    groups: list[tuple[str, list[str]]] = []
    for line in src.splitlines():
        m = re.match(r"^    # (.+)$", line)
        if m:
            groups.append((m.group(1).strip(), []))
            continue
        m = re.match(r"^    (\w+): ", line)
        if m and m.group(1) in RunConfig.model_fields and groups:
            groups[-1][1].append(m.group(1))
    return groups


def configuration_page() -> str:
    out = [HEADER, "# Configuration reference\n\n",
           "Every run setting, as used in run config files (YAML or JSON) and as `cba run` options. "
           "In config files use the key as written below. On the command line, write it with dashes, "
           "for example `sample_size` becomes `--sample-size`. True/false settings take "
           "`--name` or `--no-name` on the command line.\n\n",
           "Settings are combined in this order, later sources win: built-in defaults, config files "
           "(in the order given with `-c`), options given on the command line. Unknown keys are an "
           "error. Relative paths are resolved from the folder you run `cba` in.\n\n"]
    listed = set()
    for title, names in _groups():
        out.append(f"## {title}\n\n| Key | Type | Default | Description |\n|---|---|---|---|\n")
        for name in names:
            f = RunConfig.model_fields[name]
            out.append(f"| `{name}` | {_type_name(f.annotation)} | {_default(f)} | {_cell(f.description or '')} |\n")
            listed.add(name)
        out.append("\n")
    missing = set(RunConfig.model_fields) - listed
    if missing:
        raise SystemExit(f"fields without a group comment in config.py: {sorted(missing)}")
    return "".join(out)


# ── CLI ────────────────────────────────────────────────────────────────────────────────────────

def _subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _summaries(parser: argparse.ArgumentParser) -> dict[str, str]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return {a.dest: a.help or "" for a in action._choices_actions}
    return {}


def _metavar(action: argparse.Action) -> str:
    if action.nargs == 0:
        return ""
    if action.choices is not None and action.metavar is None:
        return "{" + ",".join(map(str, action.choices)) + "}"
    mv = action.metavar or (action.dest if not action.option_strings else action.dest.upper())
    if action.nargs in ("+", "*"):
        return f"{mv} ..."
    return str(mv)


def _option_default(action: argparse.Action) -> str:
    if isinstance(action, argparse.BooleanOptionalAction) or action.nargs == 0:
        return "off" if action.default in (False, None) else "on"
    if action.default in (None, argparse.SUPPRESS):
        return ""
    return f"`{action.default}`"


def cli_page() -> str:
    parser = build_parser()
    summaries = _summaries(parser)
    out = [HEADER, "# Command-line reference\n\n",
           "All commands are run as `cba <command> ...`. Every command also accepts `-h` / `--help`. "
           "`cba --version` prints the installed version.\n\n",
           "| Command | Purpose |\n|---|---|\n"]
    subs = _subcommands(parser)
    for name in subs:
        out.append(f"| [`{name}`](#cba-{name}) | {_cell(summaries.get(name, ''))} |\n")
    out.append("\n")
    for name, sp in subs.items():
        out.append(f"## cba {name}\n\n")
        if sp.description:
            out.append(_cell(sp.description).replace("\\|", "|") + "\n\n")
        positionals = [a for a in sp._actions if not a.option_strings and a.dest != "help"]
        required = [a for a in sp._actions if a.option_strings and a.required]
        usage = ["cba", name]
        usage += [f"{a.option_strings[-1]} {_metavar(a)}".strip() for a in required]
        has_optional = any(a.option_strings and not a.required and a.dest != "help" for a in sp._actions)
        if has_optional:
            usage.append("[options]")
        for a in positionals:
            mv = _metavar(a)
            usage.append(f"[{mv}]" if a.nargs == "?" else mv)
        out.append("    " + " ".join(usage) + "\n\n")
        if positionals:
            out.append("| Argument | Description |\n|---|---|\n")
            for a in positionals:
                out.append(f"| `{_metavar(a)}` | {_cell(a.help or '')} |\n")
            out.append("\n")
        for group in sp._action_groups:
            actions = [a for a in group._group_actions if a.option_strings and a.dest != "help"]
            if not actions:
                continue
            title = group.title if group.title not in ("options", "optional arguments") else "Options"
            out.append(f"**{title[:1].upper() + title[1:]}**\n\n")
            if name == "run" and group.title.startswith("run settings"):
                out.append("Each option sets the run setting of the same name, see the "
                           "[configuration reference](configuration.md). Not given means: "
                           "taken from the config files, else the built-in default.\n\n")
            out.append("| Option | Value | Default | Description |\n|---|---|---|---|\n")
            for a in actions:
                if isinstance(a, argparse.BooleanOptionalAction):
                    opts = " / ".join(f"`{o}`" for o in a.option_strings)
                    value = ""
                    default = "from config" if name == "run" else _option_default(a)
                else:
                    opts = ", ".join(f"`{o}`" for o in a.option_strings)
                    value = f"`{_metavar(a)}`" if _metavar(a) else ""
                    default = _option_default(a)
                    if name == "run" and group.title.startswith("run settings"):
                        default = "from config"
                req = " (required)" if a.required else ""
                rep = " Repeatable." if isinstance(a, argparse._AppendAction) and "repeatable" not in (a.help or "").lower() else ""
                out.append(f"| {opts} | {value} | {default} | {_cell((a.help or '') + req)}{rep} |\n")
            out.append("\n")
    return "".join(out)


# ── templates ──────────────────────────────────────────────────────────────────────────────────

def templates_page() -> str:
    out = [HEADER, "# Prompt templates\n\n",
           "A template supplies the domain wording of the system prompt. A codebook can override any of "
           "these strings in its `prompt:` block. Built-in templates are frozen: their wording never "
           "changes, so a run that records a template name can always be reproduced.\n\n",
           "Use a template with `prompt_template: <name>` in a run config, or "
           "`--template <name>` with `cba render`, `cba validate` and `cba check-invariance`. "
           "You can also give the path of your own template YAML file with the same four keys.\n\n"]
    for name in available_templates():
        t = load_template(name)
        out.append(f"## `{name}`\n\n| Key | Text |\n|---|---|\n")
        for k in ("role", "task", "rules_heading", "reasoning_example"):
            out.append(f"| `{k}` | `{t[k]}` |\n")
        out.append("\n")
    return "".join(out)


PAGES = {
    "docs/reference/configuration.md": configuration_page,
    "docs/reference/cli.md": cli_page,
    "docs/reference/templates.md": templates_page,
}


def main(argv: list[str] | None = None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = []
    for rel, build in PAGES.items():
        path = ROOT / rel
        content = build()
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("out of date, run `python scripts/gen_reference.py`: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
